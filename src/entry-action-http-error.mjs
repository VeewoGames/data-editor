export function entryActionHttpStatus(error) {
  const code = typeof error?.code === "string" ? error.code : "";
  if (code === "ENTRY_ACTION_PROJECT_UNKNOWN") return 404;
  if (BAD_REQUEST_CODES.has(code)) return 400;
  if (CONFLICT_CODES.has(code)) return 409;
  if (isEntryActionDomainCode(code)) return 500;
  return Number.isInteger(error?.status) ? error.status : 500;
}

function isEntryActionDomainCode(code) {
  return code.startsWith("CANDIDATE_CREATE_") || code.startsWith("ENTRY_ACTION_")
    || code.startsWith("EXACT_ARTIFACT_") || code.startsWith("PROJECT_SKILL_")
    || code.startsWith("PROJECT_TRANSACTION_") || code.startsWith("COMMIT_JOURNAL_");
}
